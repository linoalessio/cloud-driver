# --- verify ---------------------------------------------------------------------------------------------


def test_verify_ok_when_port_listens(ctx: Context, remote: FakeRemote) -> None:
    remote.ok("ss -ltn")
    remote.ok("systemctl is-active --quiet clamav-freshclam")
    result = _fast(ClamAvStep()).verify(ctx)
    assert result.ok
    assert result.detail == "clamd listening on 127.0.0.1:3310"
    assert remote.ran("</dev/tcp/127.0.0.1/3310")


def test_verify_warns_when_freshclam_is_down(ctx: Context, remote: FakeRemote) -> None:
    remote.ok("ss -ltn")
    result = _fast(ClamAvStep()).verify(ctx)
    assert result.ok
    assert "WARN clamav-freshclam is not active" in result.detail


def test_verify_warns_but_passes_when_socket_active_and_still_loading(ctx: Context, remote: FakeRemote) -> None:
    remote.ok("systemctl is-active --quiet clamav-daemon.socket")
    remote.ok("systemctl is-active --quiet clamav-freshclam")
    result = _fast(ClamAvStep()).verify(ctx)
    assert result.ok
    assert result.detail.startswith("WARN clamd is not accepting connections on 127.0.0.1:3310")
    assert "clamav-daemon.socket is active" in result.detail


def test_verify_fails_when_socket_inactive(ctx: Context, remote: FakeRemote) -> None:
    remote.ok("systemctl --no-pager --lines=10 status", "x clamav-daemon.socket - Socket for Clam AntiVirus\n     Active: failed (Result: exit-code)\n")
    result = _fast(ClamAvStep()).verify(ctx)
    assert not result.ok
    assert "clamav-daemon.socket is not active" in result.detail
    assert "Active: failed" in result.detail


def test_verify_polls_until_deadline(ctx: Context, remote: FakeRemote) -> None:
    answers = iter([1, 1, 0])
    remote.on("ss -ltn", lambda cmd, inp: next(answers))
    remote.ok("systemctl is-active --quiet clamav-freshclam")
    step = ClamAvStep()
    step.poll_timeout = 5.0
    step.poll_interval = 0.0
    result = step.verify(ctx)
    assert result.ok
    assert remote.count("ss -ltn") == 3


