from fake_remote import FakeRemote

DEBIAN_DEFAULT_CONF = (
    "# Automatically Generated by clamav-daemon postinst\n"
    "LocalSocket /var/run/clamav/clamd.ctl\n"
    "StreamMaxLength 25M\n"
    "MaxFileSize 25M\n"
    "MaxScanSize 100M\n"
    "#TCPSocket 3310\n"
    "LogFile /var/log/clamav/clamav.log\n"
)

PROVISIONED_CONF = (
    "LocalSocket /var/run/clamav/clamd.ctl\n"
    "StreamMaxLength 128M\n"
    "MaxFileSize 128M\n"
    "MaxScanSize 300M\n"
)


def _installed(remote: FakeRemote) -> None:
    remote.ok("dpkg-query -W -f='${Status}' clamav-daemon", "install ok installed")
    remote.ok("dpkg-query -W -f='${Status}' clamav-freshclam", "install ok installed")


def _provisioned(remote: FakeRemote) -> None:
    """A box where everything is already in place."""
    _installed(remote)
    remote.files[DROP_IN_PATH] = render_drop_in("127.0.0.1", 3310)
    remote.files[CLAMD_CONF] = PROVISIONED_CONF
    remote.ok("systemctl is-enabled --quiet")
    remote.ok("systemctl is-active --quiet clamav-daemon.socket")
    remote.ok("systemctl is-active --quiet clamav-freshclam")


def _fast(step: ClamAvStep) -> ClamAvStep:
    step.poll_timeout = 0.0
    step.poll_interval = 0.0
    return step


# --- pure helpers -------------------------------------------------------------------------------------


def test_listen_address_maps_localhost_and_refuses_ipv6() -> None:
    assert listen_address("127.0.0.1") == "127.0.0.1"
    assert listen_address("localhost") == "127.0.0.1"
    assert listen_address("") == "127.0.0.1"
    with pytest.raises(StepError):
        listen_address("::1")


def test_render_drop_in_has_exactly_one_ipv4_listener() -> None:
    text = render_drop_in("127.0.0.1", 3310)
    assert text == "[Socket]\nListenStream=127.0.0.1:3310\n"
    assert drop_in_listeners(text) == ["127.0.0.1:3310"]
    assert drop_in_is_current(text, "127.0.0.1", 3310)
    assert not drop_in_is_current(text, "127.0.0.1", 3311)
    assert not drop_in_is_current(None, "127.0.0.1", 3310)


def test_drop_in_with_a_second_ipv6_listener_is_not_current() -> None:
    text = "[Socket]\nListenStream=127.0.0.1:3310\nListenStream=[::1]:3310\n"
    assert drop_in_listeners(text) == ["127.0.0.1:3310", "[::1]:3310"]
    assert not drop_in_is_current(text, "127.0.0.1", 3310)


def test_clamd_limit_values_ignore_commented_lines() -> None:
    values = clamd_limit_values("StreamMaxLength 25M\n#MaxFileSize 25M\nMaxScanSize\t300M\n")
    assert values == {"StreamMaxLength": "25M", "MaxFileSize": None, "MaxScanSize": "300M"}
    assert clamd_limit_values(None) == {"StreamMaxLength": None, "MaxFileSize": None, "MaxScanSize": None}


def test_apply_clamd_limits_replaces_in_place_and_appends_missing() -> None:
    wanted = wanted_limits(InstallPlan())
    result = apply_clamd_limits(DEBIAN_DEFAULT_CONF, wanted)
    lines = result.splitlines()
    assert lines[2] == "StreamMaxLength 128M"
    assert lines[3] == "MaxFileSize 128M"
    assert lines[4] == "MaxScanSize 300M"
    assert lines[0] == "# Automatically Generated by clamav-daemon postinst"
    assert "#TCPSocket 3310" in lines
    assert result.endswith("\n")
    assert stale_limits(result, wanted) == []
    assert apply_clamd_limits(result, wanted) == result

    appended = apply_clamd_limits("LocalSocket /var/run/clamav/clamd.ctl\n#MaxFileSize 25M\n", wanted)
    assert appended == (
        "LocalSocket /var/run/clamav/clamd.ctl\n#MaxFileSize 25M\n"
        "StreamMaxLength 128M\nMaxFileSize 128M\nMaxScanSize 300M\n"
    )
    assert apply_clamd_limits("", wanted) == "StreamMaxLength 128M\nMaxFileSize 128M\nMaxScanSize 300M\n"


def test_stale_limits_compares_sizes_not_spelling() -> None:
    wanted = wanted_limits(InstallPlan())
    assert stale_limits(DEBIAN_DEFAULT_CONF, wanted) == ["StreamMaxLength", "MaxFileSize", "MaxScanSize"]
    assert stale_limits("StreamMaxLength 131072K\nMaxFileSize 128M\nMaxScanSize 300M\n", wanted) == []
    assert stale_limits(None, wanted) == ["StreamMaxLength", "MaxFileSize", "MaxScanSize"]


