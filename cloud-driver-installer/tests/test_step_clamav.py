def test_check_needs_apply_on_bare_box(ctx: Context, remote: FakeRemote) -> None:
    result = ClamAvStep().check(ctx)
    assert result.status is StepStatus.NEEDS_APPLY
    assert "install clamav-daemon, clamav-freshclam" in result.detail
    assert f"write {DROP_IN_PATH} (ListenStream=127.0.0.1:3310)" in result.detail
    assert "StreamMaxLength 128M" in result.detail and CLAMD_CONF in result.detail
    assert "enable clamav-daemon.socket" in result.detail
    assert ctx.discovered.clamd_installed is False
    # read-only: nothing written, nothing installed, no restart
